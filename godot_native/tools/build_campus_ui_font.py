#!/usr/bin/env python3
"""Build the OFL Campus UI Sans SC subset. No network, personal fonts or saves.

Requires fonttools==4.61.1. Supply the original TTC via --source. The original
file is not redistributed. --check regenerates in memory and checks the committed
font and coverage manifest. Run after runtime copy/source changes.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path

import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "godot_native/ui_assets/fonts"
SOURCE_SHA256 = "b76b0433203017ca80401b2ee0dd69350349871c4b19d504c34dbdd80541690a"
TOOL_VERSION = "4.61.1"
FAMILY = "Campus UI Sans"
POSTSCRIPT = "CampusUISans-Regular"
INPUT_ROOTS = ("src", "godot_native/scripts", "godot_native/data/native")
EXTENSIONS = {".json", ".gd", ".ts", ".tsx", ".tscn", ".tres"}
RANGES = ((0x20, 0x24F), (0x2000, 0x206F), (0x3000, 0x303F), (0xFF00, 0xFFEF))


def sha(data):
    return hashlib.sha256(data).hexdigest()


def json_text(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for key, item in value.items():
            yield key
            yield from json_text(item)
    elif isinstance(value, list):
        for item in value:
            yield from json_text(item)


def build(source):
    if fontTools.__version__ != TOOL_VERSION:
        raise SystemExit(f"Use fonttools=={TOOL_VERSION}; found {fontTools.__version__}")
    if sha(source.read_bytes()) != SOURCE_SHA256:
        raise SystemExit("Unexpected source TTC SHA256; do not silently change font provenance")
    font = TTFont(source, fontNumber=2, recalcTimestamp=False)
    if font['name'].getDebugName(1) != "Noto Sans CJK SC":
        raise SystemExit("Collection face 2 must be Simplified Chinese")
    cmap = font.getBestCmap()
    requested = {cp for first, last in RANGES for cp in range(first, last + 1)}
    source_chars = set()
    inputs = []
    for directory in INPUT_ROOTS:
        for path in sorted((ROOT / directory).rglob("*")):
            if not path.is_file() or path.suffix not in EXTENSIONS:
                continue
            raw = path.read_bytes()
            content = raw.decode("utf-8")
            source_chars.update(map(ord, content))
            if path.suffix == ".json":
                for text in json_text(json.loads(content)):
                    source_chars.update(map(ord, text))
            inputs.append({"path": path.relative_to(ROOT).as_posix(), "sha256": sha(raw)})
    requested.update(source_chars)
    present = requested & cmap.keys()
    missing = requested - cmap.keys()
    missing_cjk = [cp for cp in source_chars - cmap.keys() if 0x3400 <= cp <= 0x9FFF or 0x20000 <= cp <= 0x3134F]
    if missing_cjk:
        raise SystemExit("Source CJK glyphs absent from upstream: " + repr(missing_cjk))
    options = subset.Options()
    options.recalc_timestamp = False
    options.canonical_order = True
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    options.layout_features = ["*"]
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=sorted(present))
    worker.subset(font)
    # Rename both OpenType names and CFF names; this TTC's SC face still carries
    # shared JP CFF naming. Retain upstream copyright and license name records.
    replacement = {1: FAMILY, 2: "Regular", 3: "CampusUISans-Regular-1.0",
                   4: FAMILY + " Regular", 6: POSTSCRIPT, 16: FAMILY,
                   17: "Regular", 18: FAMILY + " Regular", 21: FAMILY, 22: "Regular"}
    for entry in font["name"].names:
        if entry.nameID in replacement:
            entry.string = replacement[entry.nameID].encode(entry.getEncoding())
    for name_id, value in replacement.items():
        font["name"].setName(value, name_id, 3, 1, 0x409)
    cff = font["CFF "].cff
    cff.fontNames = [POSTSCRIPT]
    top = cff.topDictIndex[0]
    top.FamilyName = FAMILY
    top.FullName = FAMILY + " Regular"
    if hasattr(top, "FDArray"):
        for index, fd in enumerate(top.FDArray):
            fd.FontName = f"{POSTSCRIPT}-FD{index}"
    buffer = io.BytesIO()
    font.save(buffer, reorderTables=True)
    data = buffer.getvalue()
    # Reopen the actual generated bytes and prove coverage, not only the request.
    result = TTFont(io.BytesIO(data), recalcTimestamp=False)
    if not present.issubset(result.getBestCmap()):
        raise SystemExit("Subset lost requested upstream glyph coverage")
    if not all(cp in result.getBestCmap() for cp in range(32, 127)):
        raise SystemExit("Printable ASCII coverage incomplete")
    report = {
        "family": FAMILY, "postscript_name": POSTSCRIPT, "format": "OpenType CFF (.otf)",
        "license": "SIL Open Font License 1.1",
        "source": {"filename": source.name, "sha256": SOURCE_SHA256, "face_index": 2,
                   "family": "Noto Sans CJK SC", "version": "2.004"},
        "fonttools_version": TOOL_VERSION,
        "inputs": inputs,
        "additional_unicode_ranges": [f"U+{a:04X}-U+{b:04X}" for a,b in RANGES],
        "requested_codepoints": len(requested), "covered_codepoints": len(present),
        "glyph_count": len(result.getGlyphOrder()), "bytes": len(data), "sha256": sha(data),
        "source_missing_nonwhitespace": [f"U+{cp:04X}" for cp in sorted(source_chars - cmap.keys()) if not chr(cp).isspace()],
        "requested_unavailable_codepoints": [f"U+{cp:04X}" for cp in sorted(missing) if not chr(cp).isspace()],
        "source_cjk_missing": [],
        "coverage_note": "Static authored runtime only. Arbitrary names, imports and new text require fallback and a rebuild; unsupported symbols are not removed from UI."
    }
    return data, (json.dumps(report, ensure_ascii=False, indent=2) + "\n").encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True, help="External, verified original NotoSansCJK-Regular.ttc")
    parser.add_argument("--check", action="store_true", help="Read-only regeneration and byte verification")
    args = parser.parse_args()
    font, manifest = build(args.source)
    outputs = {"CampusUISans-Regular.otf": font, "campus_ui_font_manifest.json": manifest}
    if args.check:
        for filename, data in outputs.items():
            if not (DEST / filename).exists() or (DEST / filename).read_bytes() != data:
                raise SystemExit(f"Out-of-date artifact: {filename}; regenerate after source changes")
    else:
        DEST.mkdir(parents=True, exist_ok=True)
        for filename, data in outputs.items():
            (DEST / filename).write_bytes(data)
    print(f"Campus UI Sans: {len(font):,} bytes; SHA256 {sha(font)}; {'verified' if args.check else 'generated'}")


if __name__ == "__main__":
    main()
