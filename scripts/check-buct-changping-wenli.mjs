#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(process.argv[2]||path.join(here,'..','godot_native'));
const campus=path.join(root,'campuses/buct_changping');
const read=p=>fs.readFileSync(path.join(campus,p));
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const profile=JSON.parse(read('data/wenli_registration.json'));
const image=read('assets/wenli_body.png');
const surface=read('data/wenli_surfaces.r8.bin');
const mask=read('data/wenli_source_removal.r8.bin');
const checks=[];
function check(ok,label){checks.push(Boolean(ok));console.log(`${ok?'PASS':'FAIL'} ${label}`);}
check(image.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10]))&&image[24]===8&&image[25]===6,'Original PNG is true 8-bit RGBA');
check(image.readUInt32BE(16)===1230&&image.readUInt32BE(20)===1278,'Immutable downloaded body dimensions');
check(hash(image)===profile.body_sha256&&profile.body_sha256==='29acba79fa0ba17512350d3db377a6b8e2f675ef683f59754d305e2dc04f6afc','Complete original web PNG bytes retained');
check(surface.length===1230*1278&&[...new Set(surface)].sort().join(',')==='1,2,3,4,5','One-byte five-surface ownership field');
check(hash(surface)===profile.surface_id_sha256,'Surface semantic data hash');
check(profile.depth_rows_raw_y.length===5&&profile.depth_rows_raw_y.every(row=>row.length===1230&&row.every(Number.isFinite)),'Five independent full-width finite foot rows');
check(profile.body_image_to_world.scale>0&&profile.body_image_to_world.rotation_degrees===0,'One positive uniform body scale and translation');
check(mask.length===109*110&&[...new Set(mask)].sort().join(',')==='0,255','Separate binary exact source ownership, including true courtyard exclusions');
check(hash(mask)===profile.source_removal.sha256,'Hand-reviewed source mask hash');
check([...mask].filter(v=>v>0).length===profile.source_removal.changed_source_pixels,'Explicit bounded original-source change count');
check(hash(read('assets/wenli_ground.png'))===profile.ground.sha256&&profile.ground.sha256==='06cdc5eeb93f1d60eccd732bbaec3b0abcd3958926cee08cb106518c1ee40990','Complete generated cleanplate original retained');
check(profile.ground.inferred_not_surveyed&&JSON.stringify(profile.ground.sampled_plain_region_raw_xywh)==='[360,380,600,600]','Only plain generated paving sample; hidden ground is explicitly inferred');
check(hash(read('assets/approved-changping.png'))==='f92a8de6ef703bab4b2e471a49acc082dd4d128d264d99d3ed1818fdb0c93707','Approved full campus PNG unchanged');
check(hash(read('data/playable_route.json'))==='7042e3511177177b9db1501b587c0593376302cf707b22bf96b110d74d6fb7c6','Original guide and navigation source unchanged');
const original=JSON.parse(read('data/layers.json')).objects.find(x=>x.id==='wenli_building');
check(JSON.stringify(profile.collision_footprints_source_xy)===JSON.stringify(original.footprints)&&original.footprints.length===3,'Exactly three existing native foot colliders frozen');
const imports=read('assets/wenli_body.png.import').toString();
check(imports.includes('mipmaps/generate=true')&&imports.includes('process/fix_alpha_border=false'),'Committed body mipmap and unchanged alpha-border import policy');
console.log(`CHANGPING_WENLI_SOURCE ${checks.filter(Boolean).length}/${checks.length} passed`);
process.exitCode=checks.every(Boolean)?0:1;
